#!/usr/bin/env bash
# Cross-compile markdawn-android + every markdawn-swift-lang-* grammar plugin
# for the four Android ABIs and drop the resulting .so's into the Gradle
# module's jniLibs. The Android sibling of build-xcframework.sh.
#
# Output (per ABI <abi> in {arm64-v8a, armeabi-v7a, x86_64, x86}):
#   android/markdawn/src/main/jniLibs/<abi>/libmarkdawn_android.so          (core)
#   android/markdawn/src/main/jniLibs/<abi>/libmarkdawn_swift_lang_<n>.so   (grammars)
#
# The core .so carries the `highlight` machinery but no baked grammars; each
# grammar plugin .so is loaded on demand at runtime by Markdawn.loadLanguage().
#
# Requirements:
#   - ANDROID_NDK_HOME pointing at an installed NDK
#   - cargo install cargo-ndk
#   - the markdawn-swift-lang-* crates generated by
#     crates/markdawn-swift/generate-plugins.sh
#
# Set LANGUAGES="rust json ..." to build a subset for incremental work
# (otherwise builds every markdawn-swift-lang-* crate found).
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
repo_root="$(cd "$here/../.." && pwd)"

if ! command -v cargo-ndk >/dev/null 2>&1; then
  echo "error: cargo-ndk not found — run 'cargo install cargo-ndk'" >&2
  exit 1
fi
if [[ -z "${ANDROID_NDK_HOME:-}" ]]; then
  echo "error: ANDROID_NDK_HOME is not set" >&2
  exit 1
fi

rustup target add \
  aarch64-linux-android armv7-linux-androideabi x86_64-linux-android i686-linux-android

# cargo-ndk ABI names (it maps each to the matching rust target).
ABIS=(arm64-v8a armeabi-v7a x86_64 x86)
abi_args=()
for abi in "${ABIS[@]}"; do
  abi_args+=(-t "$abi")
done

jni_libs="$repo_root/android/markdawn/src/main/jniLibs"
mkdir -p "$jni_libs"

# ---------- Core library ----------

echo "==> building markdawn-android core for ${ABIS[*]}"
cargo ndk "${abi_args[@]}" -o "$jni_libs" \
  build --release -p markdawn-android \
  --manifest-path "$repo_root/Cargo.toml"

# ---------- Grammar plugins ----------

# Resolve the plugin list. LANGUAGES env-var wins; otherwise enumerate
# everything generated under crates/markdawn-swift-lang-*.
plugins=()
if [[ -n "${LANGUAGES:-}" ]]; then
  for name in $LANGUAGES; do
    plugins+=("$name")
  done
else
  for d in "$repo_root"/crates/markdawn-swift-lang-*; do
    [[ -d "$d" ]] || continue
    plugins+=("$(basename "$d" | sed 's/^markdawn-swift-lang-//')")
  done
fi

if [[ ${#plugins[@]} -eq 0 ]]; then
  echo "==> no grammar plugins found (run crates/markdawn-swift/generate-plugins.sh first)" >&2
else
  echo "==> building ${#plugins[@]} grammar plugins: ${plugins[*]}"
  # One cargo-ndk invocation with -p per plugin — cargo parallelizes.
  pkg_args=()
  for name in "${plugins[@]}"; do
    pkg_args+=(-p "markdawn-swift-lang-$name")
  done
  cargo ndk "${abi_args[@]}" -o "$jni_libs" \
    build --release "${pkg_args[@]}" \
    --manifest-path "$repo_root/Cargo.toml"
fi

# ---------- Summary ----------

echo
echo "==> jniLibs contents:"
du -sh "$jni_libs"/* 2>/dev/null | sort -h
